def main():
    conn = sqlite3.connect(DB)
    cur = conn.cursor()

    for tid, name, cover, remark in NEW_TYPES:
        cur.execute('INSERT OR REPLACE INTO filmtype (tid, name, cover, remark) VALUES (?,?,?,?)',
                    (tid, name, cover, remark))

    added = 0
    for tid, films in NEW_FILMS.items():
        for title, en, cover, year, director, cast, rating, desc, cc in films:
            exists = cur.execute('SELECT 1 FROM films WHERE title=? AND tid=?', (title, tid)).fetchone()
            if exists:
                continue
            cur.execute('''INSERT INTO films (title, tid, cover, year, author, present, describes, rating, commentscount)
                           VALUES (?,?,?,?,?,?,?,?,?)''',
                        (title, tid, cover, year, director, cast, desc, rating, cc))
            added += 1

    conn.commit()
    print('新增影片：', added)
    for tid, n in cur.execute('SELECT tid, COUNT(*) FROM films GROUP BY tid'):
        name = cur.execute('SELECT name FROM filmtype WHERE tid=?', (tid,)).fetchone()[0]
        print(f'  {tid} {name}: {n} 部')
    print('总计：', cur.execute('SELECT COUNT(*) FROM films').fetchone()[0])
    conn.close()


if __name__ == '__main__':
    main()
