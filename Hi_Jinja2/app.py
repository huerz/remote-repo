from flask import Flask
from flask import render_template

# ============================================================================
# 本文件接口清单（单文件 Flask + Jinja2 模板练习）
# ----------------------------------------------------------------------------
#   GET /    渲染首页模板 templates/index.html
#            传入模板变量 users = [{name, age}, ...]，模板里用 {% for %} 遍历
# ----------------------------------------------------------------------------
# 启动：.venv\Scripts\python.exe app.py
# 访问：http://127.0.0.1:5814/
# ============================================================================

app = Flask(__name__)

# ============================================================================
# 【接口】首页
# 调用方式：GET /
# 参数：无
# 返回：HTML 页面（非 JSON）
# ============================================================================
@app.route('/')
def index():
    users = [
        {'name': 'Alice', 'age': 25},
        {'name': 'Bob', 'age': 30},
        {'name': 'Charlie', 'age': 35}
    ]
    return render_template('index.html', users=users)

if __name__ == '__main__':
    app.run(port=5814)