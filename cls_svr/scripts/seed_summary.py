def main(argv: list[str] | None = None) -> int:
    """把简介写入 classics.summary。

    Args:
        argv: 命令行参数，支持 --dry-run、--force。

    Returns:
        进程退出码：0 成功，1 失败。
    """
    parser = argparse.ArgumentParser(description='导入作品内容简介')
    parser.add_argument('--dry-run', action='store_true', help='只统计，不写库')
    parser.add_argument('--force', action='store_true', help='覆盖已有简介')
    args = parser.parse_args(argv)

    if args.dry_run:
        print(f'待写入简介 {len(SUMMARIES)} 条，平均 {sum(len(v) for v in SUMMARIES.values()) // len(SUMMARIES)} 字')
        return 0

    conn = pymysql.connect(host='127.0.0.1', user='root', password='123456',  # 先确保表里有 summary 字段（老库第一次跑会自动补上）
                           database='classicsdb', charset='utf8')
    try:
        with conn.cursor() as cur:
            cur.execute("SHOW COLUMNS FROM classics LIKE 'summary'")
            if not cur.fetchone():
                cur.execute("ALTER TABLE classics ADD COLUMN summary VARCHAR(500) "
                            "NULL COMMENT '内容简介'")
                conn.commit()
                print('[建表] classics 已添加 summary 字段')
    finally:
        conn.close()

    from app import create_app, db
    from app.model.models import Classics

    app = create_app()
    with app.app_context():
        added = updated = 0
        for cid, text in SUMMARIES.items():
            classic = Classics.query.get(cid)
            if classic is None:
                continue
            if classic.summary and not args.force:
                continue
            classic.summary = text
            added += 1
        db.session.commit()
        total = Classics.query.count()
        with_summary = Classics.query.filter(Classics.summary.isnot(None)).count()
        print(f'[完成] 写入简介 {added} 条；表内 {total} 部作品，其中 {with_summary} 部有简介')
    return 0


if __name__ == '__main__':
    sys.exit(main())